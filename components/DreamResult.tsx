// 로또 번호 추천 (재미용)
const getLottoNumbers = (keywords: string[], luckyNumber: number): number[] => {
  const baseNumbers = [luckyNumber];
  const keywordSum = keywords.reduce((sum, k) => sum + k.charCodeAt(0), 0);

  while (baseNumbers.length < 6) {
    const newNum = ((keywordSum * baseNumbers.length + Date.now()) % 45) + 1;
    if (!baseNumbers.includes(newNum)) {
      baseNumbers.push(newNum);
    }
  }
  return baseNumbers.sort((a, b) => a - b);
};

